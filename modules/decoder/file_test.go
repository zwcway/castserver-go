func TestNoSpeaker(t *testing.T) {
	logger := log.NewStdLog()

	ctx := utils.NewContext().WithLogger(logger)

	common.Init(ctx)
	line := speaker.NewLine("default")
	sp, _ := speaker.NewSpeaker("", speaker.DefaultLineID, audio.ChannelBackCenter)
	line.AppendSpeaker(sp)

	defer line.Input.Close()

	stream.BusResample.Register(func(resample *stream.ResampleElement, format *audio.Format) error {
		if format == nil {
			*resample = decoder.NewResample(audio.InternalFormat())
		} else {
			*resample = decoder.NewResample(*format)
		}
		return nil
	})

	fs := decoder.FileStreamer(line.UUID)
	if err := fs.OpenFile("./ffmpeg/test/test_44100_fltp_mono.mp3"); err != nil {
		t.Error(err)
	}
	defer fs.Close()
	fmt.Println("格式", fs.AudioFormat())

	fs.SetPause(false)

	sample := stream.NewSamples(128, line.Output)

	line.Input.Stream(sample)

	want := []uint8{
		0x00, 0x00, 0x00, 0x40, 0x9f, 0x1e, 0x67, 0xbd, 0x00, 0x00, 0x00, 0x80, 0xf5, 0x03, 0x6c, 0xbd,
		0x00, 0x00, 0x00, 0x80, 0x73, 0x4d, 0x70, 0xbd, 0x00, 0x00, 0x00, 0x00, 0x2d, 0x68, 0x72, 0xbd,
		0x00, 0x00, 0x00, 0x80, 0xa5, 0x32, 0x74, 0xbd, 0x00, 0x00, 0x00, 0xc0, 0x5e, 0x6f, 0x75, 0xbd,
		0x00, 0x00, 0x00, 0xe0, 0x12, 0xc6, 0x75, 0xbd, 0x00, 0x00, 0x00, 0xc0, 0x24, 0xd1, 0x74, 0xbd,
		0x00, 0x00, 0x00, 0x80, 0x84, 0x39, 0x72, 0xbd, 0x00, 0x00, 0x00, 0xc0, 0x3e, 0xa1, 0x6b, 0xbd,
		0x00, 0x00, 0x00, 0x80, 0xb1, 0xab, 0x5e, 0xbd, 0x00, 0x00, 0x00, 0x00, 0xa0, 0x3f, 0x03, 0xbd,
		0x00, 0x00, 0x00, 0x00, 0x37, 0x43, 0x60, 0x3d, 0x00, 0x00, 0x00, 0xe0, 0x90, 0x78, 0x70, 0x3d,
		0x00, 0x00, 0x00, 0xa0, 0xb9, 0x3d, 0x78, 0x3d, 0x00, 0x00, 0x00, 0x40, 0x8b, 0x11, 0x7f, 0x3d,
		0x00, 0x00, 0x00, 0x80, 0xd0, 0x77, 0x82, 0x3d, 0x00, 0x00, 0x00, 0xc0, 0x92, 0x17, 0x85, 0x3d,
		0x00, 0x00, 0x00, 0xa0, 0xc7, 0xb0, 0x87, 0x3d, 0x00, 0x00, 0x00, 0x80, 0x58, 0x8e, 0x8a, 0x3d,
	}
	assert.Equal(t, want, sample.ChannelIndexBytes(0)[:160])

	line.Input.PlayerEle.AddPCMWithChannel(audio.ChannelFrontLeft, sounds.Format(), sounds.FrontLeft())
	line.Input.Stream(sample)
}
